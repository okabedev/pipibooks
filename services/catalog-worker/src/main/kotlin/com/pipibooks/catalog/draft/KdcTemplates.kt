package com.pipibooks.catalog.draft

/** KDC 대분류(0~9)별 "이런 분께" 문장 템플릿. 각 두 문장이다. */
object KdcTemplates {
    val labels =
        mapOf(
            '0' to "총류",
            '1' to "철학",
            '2' to "종교",
            '3' to "사회과학",
            '4' to "자연과학",
            '5' to "기술과학",
            '6' to "예술",
            '7' to "언어",
            '8' to "문학",
            '9' to "역사",
        )

    val default = listOf("새로운 책을 찾고 있는 분께 권합니다.", "표지 너머의 이야기가 궁금한 분이라면 한번 펼쳐 보세요.")

    private val byMajor =
        mapOf(
            '0' to listOf("세상의 지식을 넓게 훑어보고 싶은 분께 권합니다.", "궁금한 것이 많은 호기심 많은 독자에게 어울립니다."),
            '1' to listOf("삶의 이유와 생각하는 방법이 궁금한 분께 권합니다.", "답보다 좋은 질문을 찾고 싶은 분에게 어울립니다."),
            '2' to listOf("믿음과 마음의 쉼을 찾고 있는 분께 권합니다.", "삶의 의미를 차분히 돌아보고 싶은 분에게 어울립니다."),
            '3' to listOf("사회와 세상이 돌아가는 방식이 궁금한 분께 권합니다.", "뉴스 너머의 맥락을 이해하고 싶은 분에게 어울립니다."),
            '4' to listOf("자연과 과학의 원리가 궁금한 분께 권합니다.", "당연하게 여겼던 것들을 새롭게 보고 싶은 분에게 어울립니다."),
            '5' to listOf("기술과 생활의 실용적인 지식을 찾는 분께 권합니다.", "배운 것을 바로 써 보고 싶은 분에게 어울립니다."),
            '6' to listOf("예술과 취향의 세계를 탐험하고 싶은 분께 권합니다.", "보고 듣고 느끼는 감각을 넓히고 싶은 분에게 어울립니다."),
            '7' to listOf("말과 글의 결을 섬세하게 살피고 싶은 분께 권합니다.", "언어로 세상을 더 정확히 보고 싶은 분에게 어울립니다."),
            '8' to listOf("이야기와 문장에 푹 빠지고 싶은 분께 권합니다.", "잠들기 전 한 편씩 천천히 읽고 싶은 분에게 어울립니다."),
            '9' to listOf("지금을 만든 과거의 이야기가 궁금한 분께 권합니다.", "사람과 장소의 기록을 따라가 보고 싶은 분에게 어울립니다."),
        )

    /** KDC 첫 글자가 0~9가 아니거나 KDC가 없으면 [default]. */
    fun forKdc(kdc: String?): List<String> = byMajor[kdc?.firstOrNull()] ?: default

    fun label(kdc: String?): String? = labels[kdc?.firstOrNull()]
}
